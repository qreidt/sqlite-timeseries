//! `tsbench prepare-timescaledb`: write the SQL the TimescaleDB scripts run, for one dataset.
//!
//! The schema mirrors what TSBS's `tsbs_load_timescaledb` creates with its default flags (a `tags`
//! table, `(tags_id, time DESC)` and `(time DESC)` indexes, 12-hour chunks), written with the
//! current `create_hypertable(..., by_range(...))` API. The TSBS loader itself is not used: it only
//! reads TSBS's own format, and it calls `create_hypertable` with `replication_factor`, an argument
//! from the multi-node era (multi-node support was removed in TimescaleDB 2.14). Data is loaded
//! from the same CSV files the SQLite engines use.
//!
//! Files written to `<data-dir>/timescaledb/`:
//! - `schema.sql`       tables, indexes, hypertables; removes any default columnstore policy
//! - `compress.sql`     enables the columnstore (segmentby tags_id, orderby time DESC) and converts every chunk
//! - `size.sql`         prints a size result as JSON (psql variables :engine, :phase)
//! - `tables.tsv`       measurement tables: name, csv file, rows, metrics
//! - `query-types.txt`  TSBS query types that fit the dataset

use anyhow::Result;
use std::fmt::Write as _;
use std::path::PathBuf;

use crate::manifest::Manifest;
use crate::{queries, timefmt};

#[derive(clap::Args)]
pub struct Args {
    #[arg(long)]
    pub data_dir: PathBuf,
    /// Chunk interval for every hypertable (TSBS default: 12h).
    #[arg(long, default_value = "12h")]
    pub chunk_interval: String,
}

fn pg_type(tsbs_type: &str) -> &'static str {
    match tsbs_type {
        "float32" => "FLOAT",
        "float64" => "DOUBLE PRECISION",
        "int64" => "BIGINT",
        "int32" => "INTEGER",
        _ => "TEXT",
    }
}

fn quote_lit(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

pub fn run(a: Args) -> Result<()> {
    let m = Manifest::load(&a.data_dir)?;
    let chunk = timefmt::pg_interval(timefmt::parse_duration_us(&a.chunk_interval)?);
    let out = a.data_dir.join("timescaledb");
    std::fs::create_dir_all(&out)?;

    // schema.sql
    let mut s = String::new();
    writeln!(
        s,
        "-- Generated by tsbench prepare-timescaledb for dataset {}.",
        m.dataset
    )?;
    writeln!(
        s,
        "-- Mirrors tsbs_load_timescaledb's default schema; see harness/src/timescaledb.rs."
    )?;
    writeln!(s, "CREATE EXTENSION IF NOT EXISTS timescaledb;\n")?;
    let tag_defs: Vec<String> = m
        .tags
        .columns
        .iter()
        .map(|c| format!("{} {}", c.name, pg_type(&c.ty)))
        .collect();
    let tag_names: Vec<&str> = m.tags.columns.iter().map(|c| c.name.as_str()).collect();
    writeln!(
        s,
        "CREATE TABLE tags (id SERIAL PRIMARY KEY, {});",
        tag_defs.join(", ")
    )?;
    writeln!(
        s,
        "CREATE UNIQUE INDEX uniq1 ON tags ({});",
        tag_names.join(", ")
    )?;
    writeln!(s, "CREATE INDEX ON tags ({});\n", tag_names[0])?;
    for t in &m.tables {
        let fields: Vec<String> = t
            .fields
            .iter()
            .map(|f| format!("{f} DOUBLE PRECISION"))
            .collect();
        let sep = if fields.is_empty() { "" } else { ", " };
        writeln!(s, "CREATE TABLE {} (time timestamptz, tags_id integer{sep}{}, additional_tags JSONB DEFAULT NULL);", t.name, fields.join(", "))?;
        writeln!(s, "CREATE INDEX ON {} (tags_id, \"time\" DESC);", t.name)?;
        writeln!(s, "CREATE INDEX ON {} (\"time\" DESC);", t.name)?;
        writeln!(s, "SELECT create_hypertable('{}', by_range('time', INTERVAL '{chunk}'), create_default_indexes => false);", t.name)?;
        writeln!(
            s,
            "-- Keep the load uncompressed; compression is a separate, timed step."
        )?;
        writeln!(
            s,
            "CALL remove_columnstore_policy('{}', if_exists => true);\n",
            t.name
        )?;
    }
    std::fs::write(out.join("schema.sql"), s)?;

    // compress.sql
    let mut c = String::new();
    writeln!(
        c,
        "-- Generated by tsbench prepare-timescaledb. Run with psql (uses \\gexec)."
    )?;
    for t in &m.tables {
        writeln!(c, "ALTER TABLE {} SET (timescaledb.enable_columnstore, timescaledb.segmentby = 'tags_id', timescaledb.orderby = 'time DESC');", t.name)?;
        writeln!(c, "SELECT format('CALL convert_to_columnstore(%L)', ch) FROM show_chunks('{}') ch \\gexec", t.name)?;
    }
    std::fs::write(out.join("compress.sql"), c)?;

    // size.sql
    let metrics = m.total_metrics();
    let total_expr = m
        .tables
        .iter()
        .map(|t| format!("hypertable_size('{}')", t.name))
        .chain(["pg_total_relation_size('tags')".to_string()])
        .collect::<Vec<_>>()
        .join(" + ");
    let objects = m
        .tables
        .iter()
        .map(|t| format!("'{0}', hypertable_size('{0}')", t.name))
        .chain(["'tags', pg_total_relation_size('tags')".to_string()])
        .collect::<Vec<_>>()
        .join(", ");
    let details = m
        .tables
        .iter()
        .map(|t| format!("'{0}', json_build_object('chunks', (SELECT count(*) FROM show_chunks('{0}')), 'columnstore', (SELECT row_to_json(x) FROM hypertable_columnstore_stats('{0}') x))", t.name))
        .collect::<Vec<_>>()
        .join(", ");
    let mut z = String::new();
    writeln!(z, "-- Generated by tsbench prepare-timescaledb. Usage: psql -At -v engine=timescaledb -v phase=raw -f size.sql")?;
    writeln!(z, "SELECT json_build_object(")?;
    writeln!(
        z,
        "  'kind', 'size', 'engine', :'engine', 'phase', :'phase', 'dataset', {},",
        quote_lit(&m.dataset)
    )?;
    writeln!(
        z,
        "  'created_at', to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"'),"
    )?;
    writeln!(z, "  'total_bytes', {total_expr},")?;
    writeln!(z, "  'objects', json_build_object({objects}),")?;
    writeln!(z, "  'rows', {}, 'metrics', {metrics},", m.total_rows())?;
    writeln!(
        z,
        "  'bytes_per_row', ({total_expr})::float8 / {},",
        m.total_rows().max(1)
    )?;
    writeln!(
        z,
        "  'bytes_per_metric', ({total_expr})::float8 / {},",
        metrics.max(1)
    )?;
    writeln!(z, "  'details', json_build_object({details}),")?;
    writeln!(z, "  'server_version', current_setting('server_version'),")?;
    writeln!(z, "  'timescaledb_version', (SELECT extversion FROM pg_extension WHERE extname = 'timescaledb')")?;
    writeln!(z, ")::text;")?;
    std::fs::write(out.join("size.sql"), z)?;

    // tables.tsv
    let mut tsv = String::new();
    for t in &m.tables {
        writeln!(tsv, "{}\t{}\t{}\t{}", t.name, t.csv, t.rows, t.metrics)?;
    }
    std::fs::write(out.join("tables.tsv"), tsv)?;

    // query-types.txt
    let mut q = String::new();
    match queries::applicable(&m) {
        Ok((ok, _)) => {
            for qt in ok {
                writeln!(q, "{}", qt.name)?;
            }
        }
        Err(e) => eprintln!("no queries for this dataset: {e}"),
    }
    std::fs::write(out.join("query-types.txt"), q)?;

    eprintln!("wrote TimescaleDB SQL to {}", out.display());
    Ok(())
}
